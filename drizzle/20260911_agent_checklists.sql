CREATE TABLE `agent_checklist_applications` (
  `id` int NOT NULL AUTO_INCREMENT,
  `templateId` int NULL,
  `transactionId` int NULL,
  `listingId` int NULL,
  `targetType` enum('transaction','listing') NOT NULL,
  `source` enum('auto','manual') NOT NULL,
  `autoKey` varchar(255) NULL,
  `templateNameSnapshot` varchar(255) NOT NULL,
  `templateDescriptionSnapshot` text NULL,
  `templateOwnerUserIdSnapshot` int NOT NULL,
  `templateTargetTypeSnapshot` enum('transaction','listing') NOT NULL,
  `templateTransactionTypeFilterSnapshot` enum('buyer','seller','dual','any') NOT NULL,
  `templateAutomaticDefaultEventSnapshot` enum('none','on_create','on_under_contract') NOT NULL,
  `targetAgentUserIdSnapshot` int NULL,
  `appliedByUserId` int NULL,
  `removedAt` timestamp NULL,
  `removedByUserId` int NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `agent_checklist_applications_autoKey_unique` (`autoKey`),
  KEY `agent_checklist_applications_transaction_idx` (`transactionId`,`removedAt`,`createdAt`),
  KEY `agent_checklist_applications_listing_idx` (`listingId`,`removedAt`,`createdAt`),
  KEY `agent_checklist_applications_template_idx` (`templateId`),
  CONSTRAINT `agent_checklist_applications_exact_target_chk` CHECK (((`transactionId` IS NOT NULL AND `listingId` IS NULL AND `targetType` = 'transaction') OR (`transactionId` IS NULL AND `listingId` IS NOT NULL AND `targetType` = 'listing'))),
  CONSTRAINT `agent_checklist_applications_template_fk` FOREIGN KEY (`templateId`) REFERENCES `agent_checklist_templates` (`id`) ON DELETE SET NULL,
  CONSTRAINT `agent_checklist_applications_transaction_fk` FOREIGN KEY (`transactionId`) REFERENCES `transactions` (`id`) ON DELETE CASCADE,
  CONSTRAINT `agent_checklist_applications_listing_fk` FOREIGN KEY (`listingId`) REFERENCES `listings` (`id`) ON DELETE CASCADE,
  CONSTRAINT `agent_checklist_applications_applied_by_fk` FOREIGN KEY (`appliedByUserId`) REFERENCES `users` (`id`) ON DELETE SET NULL,
  CONSTRAINT `agent_checklist_applications_removed_by_fk` FOREIGN KEY (`removedByUserId`) REFERENCES `users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

