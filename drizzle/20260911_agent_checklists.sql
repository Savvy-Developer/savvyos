CREATE TABLE `agent_checklist_templates` (
  `id` int NOT NULL AUTO_INCREMENT,
  `ownerUserId` int NOT NULL,
  `name` varchar(255) NOT NULL,
  `description` text NULL,
  `targetType` enum('transaction','listing') NOT NULL,
  `transactionTypeFilter` enum('buyer','seller','dual','any') NOT NULL DEFAULT 'any',
  `automaticDefaultEvent` enum('none','on_create','on_under_contract') NOT NULL DEFAULT 'none',
  `archivedAt` timestamp NULL,
  `archivedByUserId` int NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `agent_checklist_templates_owner_archived_idx` (`ownerUserId`,`archivedAt`),
  KEY `agent_checklist_templates_auto_match_idx` (`ownerUserId`,`targetType`,`automaticDefaultEvent`,`archivedAt`),
  CONSTRAINT `agent_checklist_templates_owner_fk` FOREIGN KEY (`ownerUserId`) REFERENCES `users` (`id`) ON DELETE CASCADE,
  CONSTRAINT `agent_checklist_templates_archived_by_fk` FOREIGN KEY (`archivedByUserId`) REFERENCES `users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `agent_checklist_template_items` (
  `id` int NOT NULL AUTO_INCREMENT,
  `templateId` int NOT NULL,
  `title` varchar(500) NOT NULL,
  `notes` text NULL,
  `sectionName` varchar(255) NOT NULL DEFAULT 'General',
  `sortOrder` int NOT NULL DEFAULT 0,
  `dueAnchor` enum('target_created','under_contract','closing','listing_live') NULL,
  `dueOffsetDays` int NOT NULL DEFAULT 0,
  `assignmentType` enum('none','owner','specific') NOT NULL DEFAULT 'none',
  `assignedUserId` int NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `agent_checklist_template_items_order_idx` (`templateId`,`sortOrder`,`id`),
  KEY `agent_checklist_template_items_assignee_idx` (`assignedUserId`),
  CONSTRAINT `agent_checklist_template_items_template_fk` FOREIGN KEY (`templateId`) REFERENCES `agent_checklist_templates` (`id`) ON DELETE CASCADE,
  CONSTRAINT `agent_checklist_template_items_assignee_fk` FOREIGN KEY (`assignedUserId`) REFERENCES `users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

